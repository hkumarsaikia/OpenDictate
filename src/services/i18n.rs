fn lookup(key: &str, lang: &str) -> Option<&'static str> {
    for (l, dict) in TRANSLATIONS {
        if *l == lang {
            for (k, v) in *dict {
                if *k == key {
                    return Some(*v);
                }
            }
            return None;
        }
    }
    None
}

/// Translates `key` for the specified `lang` code.
///
/// Falls back to English (`en`) if the key is missing in `lang` or if `lang` is unknown.
/// If `key` is missing in English as well, returns `key` itself.
pub fn tr<'a>(key: &'a str, lang: &str) -> &'a str {
    if let Some(val) = lookup(key, lang) {
        return val;
    }
    if lang != "en" {
        if let Some(val) = lookup(key, "en") {
            return val;
        }
    }
    key
}

/// Returns true if the specified language is Right-to-Left (e.g. Arabic `ar`).
pub fn is_rtl(lang: &str) -> bool {
    LANGUAGES
        .iter()
        .find(|m| m.code == lang)
        .map(|m| m.rtl)
        .unwrap_or(false)
}
